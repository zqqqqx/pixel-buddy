# PlatformIO pre-script: packs the wake word models listed in src/config.h into
# srmodels.bin and adds it to the upload at the "model" partition offset. Its size and SHA-256 go into
# src/models_sha.h: a robot updated over WiFi fetches the matching models (pixel-models.bin, update.cpp).
import hashlib, os, re, subprocess, sys
Import("env")

proj = env.subst("$PROJECT_DIR")
build = env.subst("$BUILD_DIR")
cfg = open(os.path.join(proj, "src", "config.h")).read()
models = re.search(r'#define\s+CFG_WAKEWORD_MODELS\s+"([^"]+)"', cfg).group(1).split()
sr = os.path.join(proj, "managed_components", "espressif__esp-sr")
out = os.path.join(build, "srmodels", "srmodels.bin")

if os.path.isdir(sr):
    os.makedirs(build, exist_ok=True)
    fake = os.path.join(build, "sdkconfig.srmodels")
    with open(fake, "w") as f:
        f.write('CONFIG_IDF_TARGET="esp32s3"\n' + "".join("CONFIG_SR_WN_%s=y\n" % m.upper() for m in models))
    subprocess.check_call([env.subst("$PYTHONEXE"), os.path.join(sr, "model", "movemodel.py"),
                           "-d1", fake, "-d2", sr, "-d3", build], stdout=subprocess.DEVNULL)
    print("srmodels: packed %s (%d KB)" % (" ".join(models), os.path.getsize(out) // 1024))
    # offset of the "model" partition from partitions.csv
    parts = open(os.path.join(proj, "partitions.csv")).read()
    off = re.search(r"^model\s*,[^,]*,[^,]*,\s*(0x[0-9a-fA-F]+)", parts, re.M).group(1)
    env.Append(FLASH_EXTRA_IMAGES=[(off, out)])
    data = open(out, "rb").read()
    sha = ",".join(str(b) for b in hashlib.sha256(data).digest())
else:
    print("srmodels: esp-sr not downloaded yet, build once more to pack the wake word model")
    data, sha = b"", "0"
hdr = ("// generated by tools/srmodels.py - do not edit\n#pragma once\n#include <stdint.h>\n"
       "#define MODELS_SIZE %d  // 0 = unknown: no update of the models\n"
       "static const uint8_t MODELS_SHA[32] = {%s};\n" % (len(data), sha))
dst = os.path.join(proj, "src", "models_sha.h")
if not os.path.exists(dst) or open(dst).read() != hdr:
    open(dst, "w").write(hdr)
