#!/usr/bin/env python3
# The brand font (Quicksand, fonts/, SIL OFL) for the display and the web interface:
#   src/font_ui.h          anti-aliased glyphs (4 bit) in four sizes for src/screen.cpp
#   web/fonts/*.woff2      subsets for the web interface and the setup page (served by the robot, works offline)
# Run after changing the sizes or the characters: python3 tools/fontgen.py  (needs Pillow and fontTools)
import io, os
from PIL import Image, ImageDraw, ImageFont
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MED, BOLD = (os.path.join(ROOT, "fonts", f) for f in ("Quicksand-Medium.ttf", "Quicksand-Bold.ttf"))
CHARS = [chr(c) for c in range(32, 127)] + list("ÄÖÜäöüßéèàçñ…–—„“”‘’·•°€")
SIZES = [("TITLE", BOLD, 30), ("LABEL", BOLD, 19), ("TEXT", MED, 16), ("SMALL", BOLD, 12)]


def glyphs(path, px):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    out = []
    for ch in CHARS:
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        data = b""
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            px4 = [(v * 15 + 127) // 255 for v in im.getdata()]
            px4 += [0] * (len(px4) & 1)
            data = bytes((px4[i] << 4) | px4[i + 1] for i in range(0, len(px4), 2))
        out.append((ord(ch), adv, w, h, box[0], box[1], data))
    return asc + desc, asc, out


def header():
    lines = ["// generated by tools/fontgen.py from fonts/Quicksand-*.ttf (SIL Open Font License, fonts/OFL.txt)",
             "#pragma once", "#include <stdint.h>", "",
             "struct UiGlyph {", "  uint16_t cp;      // Unicode", "  uint8_t adv, w, h;",
             "  int8_t x, y;      // of the bitmap: from the pen position / from the top of the line",
             "  uint32_t off;     // into the data: w * h 4-bit alpha values, two per byte, row by row", "};",
             "struct UiFont {", "  uint8_t height, ascent;", "  uint16_t n;", "  const UiGlyph* g;",
             "  const uint8_t* data;", "};", ""]
    for name, path, px in SIZES:
        height, asc, gs = glyphs(path, px)
        blob, table = b"", []
        for cp, adv, w, h, x, y, data in gs:
            table.append("{%d,%d,%d,%d,%d,%d,%d}" % (cp, adv, w, h, x, y, len(blob)))
            blob += data
        lines.append("static const UiGlyph G_%s[] = {%s};" % (name, ",".join(table)))
        lines.append("static const uint8_t D_%s[] = {%s};" % (name, ",".join(str(b) for b in blob)))
        lines.append("static const UiFont F_%s = {%d, %d, %d, G_%s, D_%s};" % (name, height, asc, len(gs), name, name))
        lines.append("")
    open(os.path.join(ROOT, "src", "font_ui.h"), "w").write("\n".join(lines))


def woff2():
    os.makedirs(os.path.join(ROOT, "web", "fonts"), exist_ok=True)
    for path, weight in ((MED, 500), (BOLD, 700)):
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["kern", "liga"]
        font = TTFont(path)
        s = subset.Subsetter(opts)
        s.populate(text="".join(CHARS))
        s.subset(font)
        font.flavor = "woff2"
        font.save(os.path.join(ROOT, "web", "fonts", "quicksand-%d.woff2" % weight))


header()
woff2()
for f in ("src/font_ui.h", "web/fonts/quicksand-500.woff2", "web/fonts/quicksand-700.woff2"):
    print(f, os.path.getsize(os.path.join(ROOT, f)))
